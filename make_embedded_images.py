"""
make_embedded_images.py
Reads whatever files config.CITY_IMAGE_FILES points at and writes their
bytes, base64-encoded, directly into `embedded_images.py`.

Run this ONCE:
    python make_embedded_images.py

After that, image_data.py loads from embedded_images.py automatically
(it takes priority over config.CITY_IMAGE_FILES) and the repo no longer
reads any image files at runtime -- no paths, no directories, nothing to
misconfigure. This is the closest thing to "images defined directly in
the code": paths are used exactly once, here, and never again.

Trade-off worth knowing: base64 inflates bytes by ~33%, so 10 images of
a few hundred KB each becomes a multi-MB Python file. That's fine for a
handful of images; don't run this over hundreds.
"""

from __future__ import annotations

import base64
import mimetypes
import os
import sys

import config


def _resolve(entry: str) -> str:
    if os.path.isabs(entry):
        return entry
    root = getattr(config, "IMAGE_ROOT", "") or ""
    return os.path.join(root, entry) if root else entry


def _mime_for(path: str, raw: bytes) -> str:
    mime, _ = mimetypes.guess_type(path)
    if mime and mime.startswith("image/"):
        return mime
    if raw[:3] == b"\xff\xd8\xff":
        return "image/jpeg"
    if raw[:8] == b"\x89PNG\r\n\x1a\n":
        return "image/png"
    return "image/png"


def main() -> int:
    out_path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "embedded_images.py")

    collected = {}
    total_bytes = 0
    missing_any = False

    for city, entries in config.CITY_IMAGE_FILES.items():
        limit = config.CITYLENS_IMAGES_PER_AGENT
        city_entries = []
        for entry in entries[:limit]:
            path = _resolve(entry)
            if not os.path.isfile(path):
                print(f"  MISSING  {city}: {os.path.abspath(path)}")
                missing_any = True
                continue
            with open(path, "rb") as f:
                raw = f.read()
            if not raw:
                print(f"  EMPTY    {city}: {os.path.abspath(path)}")
                missing_any = True
                continue
            b64 = base64.b64encode(raw).decode("ascii")
            city_entries.append((b64, _mime_for(path, raw)))
            total_bytes += len(raw)
            print(f"  ok       {city}: {os.path.abspath(path)} ({len(raw):,} bytes)")
        collected[city] = city_entries

    if not any(collected.values()):
        print(
            "\nNo images could be read -- nothing written. Fix the paths in "
            "config.CITY_IMAGE_FILES (or set IMAGE_ROOT) and re-run."
        )
        return 1

    with open(out_path, "w") as f:
        f.write('"""\nembedded_images.py -- AUTO-GENERATED by make_embedded_images.py.\n\n')
        f.write("Base64 image bytes baked directly into source, so the pipeline\n")
        f.write("reads no image files at runtime. Regenerate by re-running\n")
        f.write("`python make_embedded_images.py`. Do not edit by hand.\n")
        f.write('"""\n\n')
        f.write("CITY_IMAGES_BASE64 = {\n")
        for city, entries in collected.items():
            f.write(f"    {city!r}: [\n")
            for b64, mime in entries:
                f.write(f"        ({b64!r}, {mime!r}),\n")
            f.write("    ],\n")
        f.write("}\n")

    size = os.path.getsize(out_path)
    print(
        f"\nWrote {out_path}\n"
        f"  {sum(len(v) for v in collected.values())} image(s), "
        f"{total_bytes:,} raw bytes -> {size:,} bytes of Python source.\n"
        f"  image_data.py will now use these automatically (no files read at runtime)."
    )
    if missing_any:
        print(
            "\nWARNING: some configured files were missing/empty (listed above) "
            "and were skipped -- the embedded set is incomplete."
        )
    return 0


if __name__ == "__main__":
    sys.exit(main())
