def test_loads_exactly_the_listed_files():
    with _ConfigGuard() as cfg, tempfile.TemporaryDirectory() as d:
        entries = _write_images(d, "NewYork", 5)
        cfg.IMAGE_ROOT = d
        cfg.CITY_IMAGE_FILES = {"New York": entries}
        cfg.CITYLENS_IMAGES_PER_AGENT = 5

        images, src = image_data.load_images_for_city("New York")
        assert len(images) == 5
        assert src == "config.CITY_IMAGE_FILES"
        b64, mime = images[0]
        assert mime == "image/png"
        assert base64.b64decode(b64) == PNG_BYTES   # raw bytes preserved


def test_does_not_scan_directories_for_unlisted_files():
    """Extra files sitting in the same folder must be IGNORED -- only
    what's explicitly listed is used."""
    with _ConfigGuard() as cfg, tempfile.TemporaryDirectory() as d:
        entries = _write_images(d, "NewYork", 5)
        # 5 more files in the same directory, deliberately NOT listed
        _write_images(d, "NewYork", 10)
        cfg.IMAGE_ROOT = d
        cfg.CITY_IMAGE_FILES = {"New York": entries[:3]}   # list only 3
        cfg.CITYLENS_IMAGES_PER_AGENT = 5

        images, _ = image_data.load_images_for_city("New York")
        assert len(images) == 3, "must use only the listed files, not everything in the dir"


