# No-network guarantee
# --------------------------------------------------------------------------
def test_image_data_makes_no_network_calls():
    """The whole point of this design: no Hugging Face HTTP requests."""
    src_path = os.path.join(os.path.dirname(__file__), "..", "image_data.py")
    with open(src_path) as f:
        src = f.read()
    assert "import datasets" not in src
    assert "from datasets" not in src
    assert "load_dataset" not in src

    # Inspect real code only -- the docstring legitimately mentions that
    # this module does NOT touch Hugging Face.
    import ast

    tree = ast.parse(src)
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            if (node.body and isinstance(node.body[0], ast.Expr)
                    and isinstance(node.body[0].value, ast.Constant)
                    and isinstance(node.body[0].value.value, str)):
                node.body[0].value.value = ""
    code_only = ast.unparse(tree)
    for banned in ("huggingface.co", "hf_hub", "snapshot_download", "requests.get", "urlopen"):
        assert banned not in code_only, f"found network-ish call `{banned}` in image_data.py"


def test_no_module_imports_datasets_anywhere():
    repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    offenders = []
    for fname in os.listdir(repo_root):
        if not fname.endswith(".py"):
            continue
        with open(os.path.join(repo_root, fname)) as f:
            src = f.read()
        if "from datasets import" in src or "import datasets" in src:
            offenders.append(fname)
    assert offenders == [], f"these modules still import `datasets`: {offenders}"


