def test_embedded_images_take_priority_over_file_list():
    """When embedded_images.py exists, it's used and NO files are read."""
    with _ConfigGuard() as cfg, tempfile.TemporaryDirectory() as d:
        repo_root = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
        emb_path = os.path.join(repo_root, "embedded_images.py")
        try:
            with open(emb_path, "w") as f:
                f.write(
                    "CITY_IMAGES_BASE64 = {\n"
                    "    'New York': [('ZW1iZWRkZWQx', 'image/png'), ('ZW1iZWRkZWQy', 'image/png')],\n"
                    "}\n"
                )
            sys.modules.pop("embedded_images", None)

            # File list points at paths that DON'T exist -- proving the
            # embedded data is what's actually used.
            cfg.IMAGE_ROOT = d
            cfg.CITY_IMAGE_FILES = {"New York": ["nope/1.png", "nope/2.png"]}
            cfg.CITYLENS_IMAGES_PER_AGENT = 5

            images, src = image_data.load_images_for_city("New York")
            assert src == "embedded_images.py"
            assert len(images) == 2
            assert images[0][0] == "ZW1iZWRkZWQx"
        finally:
            if os.path.exists(emb_path):
                os.remove(emb_path)
            sys.modules.pop("embedded_images", None)


