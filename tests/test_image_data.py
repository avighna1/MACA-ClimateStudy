"""
Tests for image_data.py -- explicit per-city image files, embedded
images, and FEMA NRI risk data.

Two properties matter most and are asserted explicitly:
  1. NO NETWORK. Nothing may import `datasets` or make an HTTP request
     to Hugging Face. A test fails loudly if `datasets` ever creeps back
     into the import graph.
  2. NO PATH GUESSING. Exactly the files listed in
     config.CITY_IMAGE_FILES are used -- no directory scanning, no
     recursive discovery. Missing files are reported individually and
     the remaining ones still load.
"""

import base64
import os
import sys
import tempfile

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..")))

import pandas as pd
import config
import image_data

PNG_BYTES = b"\x89PNG\r\n\x1a\n" + b"fakepngdata" * 5
JPG_BYTES = b"\xff\xd8\xff" + b"fakejpgdata" * 5


def _write_images(root, folder, count, ext=".png", content=PNG_BYTES):
    """Creates `count` image files and returns their RELATIVE entries
    (as they'd appear in config.CITY_IMAGE_FILES)."""
    d = os.path.join(root, folder)
    os.makedirs(d, exist_ok=True)
    entries = []
    for i in range(1, count + 1):
        with open(os.path.join(d, f"{i}{ext}"), "wb") as f:
            f.write(content)
        entries.append(f"{folder}/{i}{ext}")
    return entries


class _ConfigGuard:
    """Saves/restores every config field these tests mutate."""

    FIELDS = ("CITY_IMAGE_FILES", "IMAGE_ROOT", "CITYLENS_IMAGES_PER_AGENT", "FEMA_NRI_LOCAL_PATH")

    def __enter__(self):
        self._saved = {f: getattr(config, f) for f in self.FIELDS}
        return config

    def __exit__(self, *exc):
        for f, v in self._saved.items():
            setattr(config, f, v)
        # embedded_images.py is generated by some tests; never leave it behind,
        # since its mere presence changes which loader path runs.
        sys.modules.pop("embedded_images", None)
        return False


