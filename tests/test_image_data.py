def test_fema_column_normalization_and_city_matching():
    df = pd.DataFrame({
        "STATE": ["New York", "New York", "California", "Texas"],
        "COUNTY": ["New York", "Kings", "San Francisco", "Harris"],
        "RISK_SCORE": [70.0, 60.0, 88.0, 20.0],
        "SOVI_SCORE": [50.0, 40.0, 70.0, 10.0],
    })
    normalized = image_data._normalize_fema_columns(df)
    assert "hazard_risk_score" in normalized.columns
    assert "social_vulnerability_index" in normalized.columns
    assert normalized["social_vulnerability_index"].max() <= 1.0   # 0-100 -> 0-1

    ny = image_data._risk_for_city(normalized, "New York")
    assert ny is not None
    hazard, sovi, dominant, n = ny
    assert n == 2                      # New York + Kings counties
    assert abs(hazard - 65.0) < 1e-6   # mean of 70 and 60

    sf = image_data._risk_for_city(normalized, "San Francisco")
    assert sf is not None
    assert abs(sf[0] - 88.0) < 1e-6
    assert sf[3] == 1                   # Harris (Texas) must not leak in


