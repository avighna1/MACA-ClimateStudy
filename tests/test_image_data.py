def test_build_city_data_falls_back_to_synthetic_risk_but_flags_it():
    with _ConfigGuard() as cfg, tempfile.TemporaryDirectory() as d:
        ny = _write_images(d, "NewYork", 2)
        sf = _write_images(d, "SanFrancisco", 2)
        cfg.IMAGE_ROOT = d
        cfg.CITY_IMAGE_FILES = {"New York": ny, "San Francisco": sf}
        cfg.CITYLENS_IMAGES_PER_AGENT = 5
        cfg.FEMA_NRI_LOCAL_PATH = os.path.join(d, "nope", "missing.csv")

        city_data = image_data.build_city_data(["New York", "San Francisco"])
        assert set(city_data.keys()) == {"New York", "San Francisco"}
        assert image_data.any_synthetic_risk(city_data) is True
        for cd in city_data.values():
            assert cd.synthetic_risk is True
            assert len(cd.images) == 2
            assert 0.0 <= cd.combined_need_score() <= 1.0
        assert image_data.cities_without_images(city_data) == []


def test_risk_text_contains_numbers_but_no_image_description():
    cd = image_data.CityData(
        city="New York",
        images=[("Zm9v", "image/png")],
        hazard_risk_score=72.5,
        social_vulnerability_index=0.61,
        dominant_hazard="Coastal Flooding",
        n_counties_matched=5,
    )
    text = cd.to_risk_text()
    assert "72.5" in text
    assert "0.61" in text
    assert "Coastal Flooding" in text
    for banned in ("visual survey", "the image shows", "depicts", "photo shows"):
        assert banned.lower() not in text.lower()


